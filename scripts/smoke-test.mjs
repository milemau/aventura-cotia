import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const url = process.env.TEST_URL || 'http://localhost:5173';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => { Math.random = () => 0.5; });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(url);
  await expect(page.locator('#loading')).toBeHidden();
  await page.screenshot({ path: 'test-results/desktop.png' });
  await page.getByRole('button', { name: 'Como isso é feito?' }).click();
  await expect(page.locator('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Fechar explicação' }).click();
  await page.getByRole('button', { name: 'Começar aventura' }).click();
  await expect(page.locator('#hud')).toBeVisible();
  await expect.poll(() => page.locator('#score').textContent()).not.toBe('0000');
  await page.keyboard.press('Space');
  await page.waitForTimeout(220);
  await page.screenshot({ path: 'test-results/jumping.png' });
  await page.keyboard.press('Escape');
  await expect(page.locator('#paused')).toBeVisible();
  const pausedScore = await page.locator('#score').textContent();
  await page.waitForTimeout(500);
  expect(await page.locator('#score').textContent()).toBe(pausedScore);
  await page.getByRole('button', { name: 'Continuar aventura' }).click();
  await page.keyboard.press('ArrowLeft');
  await expect.poll(async () => Number(await page.locator('#coins').textContent()), { timeout: 18000 }).toBeGreaterThan(0);
  await page.screenshot({ path: 'test-results/playing.png' });
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('#result')).toBeVisible({ timeout: 18000 });
  expect(Number((await page.locator('#final-score').textContent()).replaceAll('.', ''))).toBeGreaterThan(0);
  await page.screenshot({ path: 'test-results/game-over.png' });
  await page.getByRole('button', { name: 'Tentar de novo' }).click();
  await expect(page.locator('#coins')).toHaveText('0');
  await page.reload();
  expect(Number((await page.locator('#best').textContent()).replaceAll('.', ''))).toBeGreaterThan(0);
  await page.getByRole('button', { name: 'Desativar som' }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Ativar som' })).toBeVisible();
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  const mobilePage = await mobile.newPage();
  mobilePage.on('pageerror', error => errors.push(error.message));
  await mobilePage.goto(url);
  await expect(mobilePage.locator('#loading')).toBeHidden();
  expect(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await mobilePage.screenshot({ path: 'test-results/mobile.png' });
  await mobilePage.getByRole('button', { name: 'Começar aventura' }).tap();
  await mobilePage.getByRole('button', { name: 'Ir para a esquerda' }).tap();
  await mobilePage.getByRole('button', { name: 'Pular', exact: true }).tap();
  await expect(mobilePage.locator('#hud')).toBeVisible();
  await mobilePage.mouse.move(180, 400);
  await mobilePage.mouse.down();
  await mobilePage.mouse.move(300, 400, { steps: 5 });
  await mobilePage.mouse.up();
  if (process.env.TEST_OFFLINE === '1') {
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.reload();
    await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true);
    await context.setOffline(true);
    await page.reload();
    await expect(page.locator('#loading')).toBeHidden();
    await page.getByRole('button', { name: 'Começar aventura' }).click();
    await expect.poll(() => page.locator('#score').textContent()).not.toBe('0000');
    console.log('Offline reload and gameplay passed.');
  }
  expect(errors).toEqual([]);
  console.log('Desktop, mobile, controls, coins, pause, game over, restart and persistence passed.');
} finally { await browser.close(); }
